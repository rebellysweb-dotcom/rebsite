// Regenerates cloudflare/seed.d1.sql from src/lib/catalog.ts so the DB seed and the built-in fallback never drift.
// Usage: node scripts/gen-seed.mjs   (Node 22.6+ strips the TypeScript types on import)
import { writeFileSync } from 'node:fs';
import { CATALOG_PRODUCTS, ADD_ONS } from '../src/lib/catalog.ts';

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const rows = [
  ...CATALOG_PRODUCTS.map((p) => ({ ...p, is_active: 1 })),
  ...ADD_ONS.map((a, i) => ({
    id: a.id, name: a.name, slug: a.slug, tag: 'Add-on', category: 'add-on', description: null,
    image_url: a.imageUrl ?? null, image_urls: [], price_usd: a.price_usd, is_active: 0, sort_order: 101 + i,
  })),
];

const values = rows
  .map((p) =>
    `  (${[p.id, p.name, p.slug, p.tag, p.category ?? null, p.description ?? null, p.image_url ?? null, JSON.stringify(p.image_urls), p.price_usd, p.is_active ? 1 : 0, p.sort_order].map(q).join(', ')})`,
  )
  .join(',\n');
const ids = rows.map((r) => q(r.id)).join(', ');
const slugs = rows.map((r) => q(r.slug)).join(', ');

const sql = `-- Rebellys D1 seed. GENERATED by scripts/gen-seed.mjs from src/lib/catalog.ts - edit the catalog, then re-run the script.
-- Apply AFTER the migrations: wrangler d1 execute rebellys-db --local --file=cloudflare/seed.d1.sql   (--remote for production)
-- Idempotent: safe to run any number of times. No credentials here; create the admin with scripts/create-admin.mjs.

-- Default single-row site settings. Runs only while the table is empty (edit later in /admin/settings).
INSERT INTO site_settings (lbp_rate, whish_number, whatsapp_number, shop_phone, shop_address, shop_email)
SELECT '89500', '', '', '+961-1-234567', 'Saydeh Street, Zalka, Lebanon', 'info@rebellys.com'
WHERE NOT EXISTS (SELECT 1 FROM site_settings);

-- Slug-collision guard: a row that owns one of the seed slugs under a DIFFERENT id (e.g. created in the admin) would
-- violate UNIQUE(slug) on the upsert below. The seed's catalog wins, so that row is removed first.
DELETE FROM products WHERE slug IN (${slugs}) AND id NOT IN (${ids});

-- ${CATALOG_PRODUCTS.length} catalog products (active) + ${ADD_ONS.length} add-ons (is_active = 0: hidden from the shop, but the order API
-- prices cart add-ons from this table). Upsert by id: re-running refreshes names, prices, photos and categories.
INSERT INTO products (id, name, slug, tag, category, description, image_url, image_urls, price_usd, is_active, sort_order)
VALUES
${values}
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name, slug = excluded.slug, tag = excluded.tag, category = excluded.category,
  description = excluded.description, image_url = excluded.image_url, image_urls = excluded.image_urls,
  price_usd = excluded.price_usd, is_active = excluded.is_active, sort_order = excluded.sort_order,
  updated_at = datetime('now');
`;

writeFileSync(new URL('../cloudflare/seed.d1.sql', import.meta.url), sql, 'utf8');
console.log(`seed written: ${CATALOG_PRODUCTS.length} products + ${ADD_ONS.length} add-ons`);
